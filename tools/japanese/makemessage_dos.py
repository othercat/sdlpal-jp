"""Generate a version-bound DOS SLF from reviewed DOS/Win/Saturn sources."""
import argparse
import hashlib
import json
import re
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

from resource_version import without_win_tag
from verify_baseline import check_inputs, sha256, slf_summary
from verify_restored_dialogues import blocks, groups, read_sources, require

TOOL_DIR = Path(__file__).resolve().parent
MANIFEST = TOOL_DIR / "dos-map.json"


def text_hash(lines):
    return hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()


def read_dos(inputs):
    sss = Path(inputs["SSS.MKF"]["path"]).read_bytes()
    offsets = struct.unpack_from("<6I", sss)
    indexes = [n[0] for n in struct.iter_unpack("<I", sss[offsets[3]:offsets[4]])]
    raw = Path(inputs["M.MSG"]["path"]).read_bytes()
    return {
        "scripts": list(struct.iter_unpack("<4H", sss[offsets[4]:offsets[5]])),
        "messages": [raw[a:b].decode("cp950") for a, b in zip(indexes, indexes[1:])],
        "objects": list(struct.iter_unpack("<6H", sss[offsets[2]:offsets[3]])),
    }


def checked_group(source, anchor, digest=None, saturn_special=False):
    start, end, first, last = anchor
    require(0 <= start <= end < len(source["scripts"]), "Script span outside resource")
    ids, text = [], []
    for position in range(start, end + 1):
        op, value, a, b = source["scripts"][position]
        if op == 0xffff:
            ids.append(value)
            text.append(source["messages"][value])
        elif op == 0x008e:
            text.append("[CLEAR MESSAGE]")
        elif (saturn_special and anchor == [8657, 8663, 3658, 3662] and
              position == 8660 and (op, value, a, b) == (0x0037, 40, 46, 8)):
            # Existing Win converter joins Saturn groups 958/959 across this
            # movement command; the following raw 008E supplies the CLEAR.
            continue
        else:
            raise ValueError(f"Unexpected operation in reviewed span {anchor}")
    require(ids and (ids[0], ids[-1]) == (first, last), f"Message IDs differ: {anchor}")
    if digest:
        require(text_hash(text) == digest, f"Source text differs: {anchor}")
    return text


def generate(dos_dir, win_dir, saturn_dir, output_dir):
    directories = [p.resolve() for p in (dos_dir, win_dir, saturn_dir)]
    output_dir = output_dir.resolve()
    require(not output_dir.exists(), "Output directory already exists; choose a new directory")
    require(output_dir.parent.is_dir(), "Output parent directory must exist")
    require(not any(output_dir == p or p in output_dir.parents for p in directories),
            "Output must be outside all input directories")
    manifest = json.loads(MANIFEST.read_text("utf-8"))
    inputs = {key: check_inputs(path, manifest["inputs"][key], key)
              for key, path in zip(("dos", "win", "saturn"), directories)}
    dos = read_dos(inputs["dos"])
    win, saturn = read_sources(inputs["win"], inputs["saturn"])
    sss = Path(inputs["win"]["sss.mkf"]["path"]).read_bytes()
    offsets = struct.unpack_from("<6I", sss)
    win_objects = list(struct.iter_unpack("<7H", sss[offsets[2]:offsets[3]]))
    runtime = groups(dos, consecutive=True)
    require(len(runtime) == len(manifest["groups"]) == 4476, "Unexpected DOS runtime group set")
    require(len(dos["objects"]) == len(win_objects) == 565, "Object identity table changed")
    # Reuse the reviewed conversion, not an arbitrary external SLF. A temporary
    # bridge permits sharing text while DOS retains an independent ID map.
    with tempfile.TemporaryDirectory(prefix="dos-japanese-", dir=output_dir.parent) as temporary:
        bridge = Path(temporary) / "win.slf"
        command = [sys.executable, "-B", "-X", "utf8", str(TOOL_DIR / "makemessage_j.py"),
                   str(win_dir), str(saturn_dir), str(bridge), "gbk"]
        process = subprocess.run(command, capture_output=True, text=True, encoding="utf-8", timeout=120)
        require(process.returncode == 0 and bridge.is_file(),
                "Win bridge conversion failed:\n" + process.stdout + process.stderr)
        win_text = bridge.read_text("utf-8")
        untagged = without_win_tag(win_text)
        require(hashlib.sha256(untagged.encode("utf-8")).hexdigest() == manifest["bridge_lf_sha256"],
                "Reviewed Win translation changed; review the DOS bridge before regenerating")
        win_map = {(first, last): text for first, last, text in blocks(bridge)}
    output = "# SDLPAL localization file\n# Version 3.1\n# Target: PAL_DOS / CP950 source resources\n"
    output += "# Generated by makemessage_dos.py; see docs/japanese-dos-mapping.md.\n"
    for version, files in inputs.items():
        for name, info in files.items():
            output += f"# SHA256 {version}/{name}: {info['sha256']}\n"
    output += "\n"
    for section in ("CREDITS", "LAYOUT", "SETTING", "WORDS"):
        matches = re.findall(rf"^\[BEGIN {section}\]\n.*?^\[END {section}\]$", win_text, re.M | re.S)
        require(len(matches) == 1, f"Expected one {section} section in Win bridge")
        output += matches[0].replace("ResourceVersion=WIN95", "ResourceVersion=DOS") + "\n\n"
    output += "[BEGIN DESCRIPTIONS]\n"
    objects, expected_descriptions = [], {}
    for description in manifest["descriptions"]:
        object_id = description["id"]
        require(object_id not in expected_descriptions, "Duplicate description object")
        require(list(dos["objects"][object_id]) == description["dos_object"] and
                list(win_objects[object_id]) == description["win_object"], "Object record differs")
        checked_group(win, description["win"])
        checked_group(saturn, description["saturn"], description["saturn_text_sha256"], True)
        key = tuple(description["win"][2:])
        lines = description["lines"]
        if object_id not in (307, 308):
            require(lines == win_map[key], f"Unreviewed description change: {object_id}")
        require(all(line and "*" not in line and "\n" not in line for line in lines) and
                len("*".join(lines)) < 512, "Invalid DOS description value")
        output += f"{object_id:04X}={'*'.join(lines)}\n"
        expected_descriptions[object_id] = lines
        # Exercise all descriptions for clipping; render only representative menus.
        draw = object_id in {149, 270, 306, 307, 308, 370, 374, 377, 384, 394}
        objects.append(f"{object_id},{int(description['kind'] == 'item')},{int(draw)}")
    require(len(expected_descriptions) == 296, "Incomplete description map")
    output += "[END DESCRIPTIONS]\n\n"
    expected, fixtures, keys = [], [], set()
    for group, review in zip(runtime, manifest["groups"]):
        anchor = [group["script_start"], group["script_end"], group["sid"], group["eid"]]
        require(anchor == review["dos"] and text_hash(group["text"]) == review["dos_text_sha256"],
                "DOS runtime order/anchor/text differs from reviewed map")
        key = group["sid"], group["eid"]
        require(key not in keys, "Duplicate DOS key")
        keys.add(key)
        if "win" in review:
            checked_group(win, review["win"], review["win_text_sha256"])
            checked_group(saturn, review["saturn"], review["saturn_text_sha256"], True)
            text = review.get("text", win_map[tuple(review["win"][2:])])
        else:
            require(review["decision"] == "preserve-source-marker" and review["text"] == group["text"],
                    "Missing source without explicit preservation decision")
            text = review["text"]
        require(text and all(line and "\ufffd" not in line for line in text), "Empty or undecodable output")
        output += f"# DOS script {anchor[0]}-{anchor[1]}; {review['decision']}\n"
        output += f"[BEGIN MESSAGE] {key[0]}\n" + "\n".join(text) + f"\n[END MESSAGE] {key[1]}\n\n"
        draw = "render_command" in review
        command = review.get("render_command", {"script": None, "words": [60, 0, 0, 0]})
        if command["script"] is not None:
            require(list(dos["scripts"][command["script"]]) == command["words"],
                    "DOS render command differs")
        fixtures.append(",".join(map(str, [*key, len(win_map.get(key, [])), len(text),
                                           int(draw), *command["words"]])))
        expected.append({"key": list(key), "text": text})
    require(len(keys) == 4476 and expected[0]["text"] == ["鍵がかかってます"], "DOS key 0 regression")
    for files in inputs.values():
        for info in files.values():
            require(sha256(Path(info["path"])) == info["sha256"], "Input changed during generation")
    output_dir.mkdir()
    (output_dir / "paljpn-dos.slf").write_text(output, "utf-8", newline="\n")
    # Keep the existing Win converter's native newline convention so its
    # historical whole-file byte checks remain meaningful.
    (output_dir / "paljpn-win.slf").write_text(win_text, "utf-8")
    # Audit-only wrong-version input: never offer it as a playable translation.
    (output_dir / "audit-wrong-win.slf").write_text(untagged, "utf-8", newline="\n")
    (output_dir / "converter.log").write_text(process.stdout + process.stderr, "utf-8")
    (output_dir / "recovery-fixtures.csv").write_text("\n".join(fixtures) + "\n", "ascii")
    (output_dir / "dos-objects.csv").write_text("\n".join(objects) + "\n", "ascii")
    (output_dir / "expected-text.json").write_text(json.dumps(expected, ensure_ascii=False), "utf-8")
    (output_dir / "expected-descriptions.json").write_text(
        json.dumps(expected_descriptions, ensure_ascii=False), "utf-8")
    report = {
        "inputs": inputs, "inputs_unchanged": True, "manifest_sha256": sha256(MANIFEST),
        "target": "DOS", "dos_source_encoding": "CP950", "decisions": manifest["decision_counts"],
        "output": slf_summary(output_dir / "paljpn-dos.slf"),
        "win_bridge": slf_summary(output_dir / "paljpn-win.slf"),
        "win_body_lf_sha256": manifest["bridge_lf_sha256"], "win_text_unchanged": True,
        "description_count": len(expected_descriptions), "dos_description_overrides": [307, 308],
        "word_identity_slots": 565, "runtime_group_count": len(keys), "dialogue_render_groups": 8,
        "wrong_win_keys_present": sum(bool(win_map.get(tuple(row["key"]))) for row in expected),
        "gameplay_acceptance": "Pending unified user acceptance; source rendering is separate.",
    }
    (output_dir / "generation.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", "utf-8")
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("dos_dir", "win_dir", "saturn_dir", "output_dir"):
        parser.add_argument(name, type=Path)
    try:
        report = generate(**vars(parser.parse_args()))
    except (OSError, ValueError, KeyError, IndexError, struct.error) as error:
        parser.exit(1, f"ERROR: {error}\n")
    print(f"PASS: {report['runtime_group_count']} DOS keys; {report['description_count']} descriptions")
